/** A new draft has nothing to list. Issued and reopened invoices keep both panels. */
export function showInvoiceHistoryPanels(status: string, eventCount: number, emailCount: number) {
  if (status !== "draft") return true;
  return eventCount > 0 || emailCount > 0;
}

export function invoiceStatusLabel(status: string) {
  switch (status) {
    case "draft":
      return "Draft";
    case "open":
      return "Open";
    case "paid":
      return "Paid";
    case "partially_paid":
      return "Partially paid";
    case "void":
      return "Void";
    default:
      return status;
  }
}

export function groupingLabel(grouping: string) {
  switch (grouping) {
    case "project":
      return invoiceCopy.groupingProject;
    case "member":
      return invoiceCopy.groupingMember;
    case "day":
      return invoiceCopy.groupingDay;
    default:
      return invoiceCopy.groupingPeriod;
  }
}
