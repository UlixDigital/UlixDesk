export const QUOTATION_VALID_MONTHS = 3;

export const QUOTATION_STATUSES = ["draft", "sent", "accepted", "declined", "expired"] as const;

export type QuotationListStatus = (typeof QUOTATION_STATUSES)[number];

export function quotationStatusLabel(status: string) {
  switch (status) {
    case "draft":
      return "Draft";
    case "sent":
      return "Sent";
    case "accepted":
      return "Accepted";
    case "declined":
      return "Declined";
    case "expired":
      return "Expired";
    default:
      return status;
  }
}
